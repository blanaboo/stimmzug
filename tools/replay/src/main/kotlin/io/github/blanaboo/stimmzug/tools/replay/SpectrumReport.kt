package io.github.blanaboo.stimmzug.tools.replay

import io.github.blanaboo.stimmzug.dsp.music.NoteNames
import java.io.File
import java.util.Locale
import kotlin.math.roundToInt

/** Writes the results of [ToneSpectrum]: every take as CSV, the levels per note as Markdown and as Kotlin table. */
object SpectrumReport {
    /** Harmonics shown in the CSV and the Markdown table. */
    private const val SHOWN = 16
    private const val VALUES_PER_LINE = 20

    fun writeCsv(notes: List<HeldNote>, file: File) {
        val header = listOf("start_s", "end_s", "note", "midi", "f0_hz", "cents", "spread_cents", "level_dbfs") +
            (1..SHOWN).map { "h$it" } + (1..SHOWN).map { "snr$it" }
        val rows = notes.map { n ->
            val peak = n.powerDb.max()
            listOf(
                f(n.startSec, 2),
                f(n.endSec, 2),
                NoteNames.germanOctaveName(n.midi),
                n.midi.toString(),
                f(n.f0Hz, 3),
                f(n.cents, 1),
                f(n.spreadCents, 1),
                f(n.levelDbfs, 1)
            ) + (0 until SHOWN).map { k -> n.powerDb.getOrNull(k)?.let { f(it - peak, 1) }.orEmpty() } +
                (0 until SHOWN).map { k -> n.snrDb.getOrNull(k)?.let { f(it, 0) }.orEmpty() }
        }
        file.writeText((listOf(header) + rows).joinToString("\n", postfix = "\n") { it.joinToString(",") })
    }

    /** German report for `docs/`: which takes were used and the first harmonics of every note. */
    fun markdown(source: String, a4Hz: Double, notes: List<HeldNote>, levels: List<NoteLevels>): String = buildString {
        appendLine("Aufnahme: `$source`, a′ = ${de(a4Hz, 0)} Hz. ${notes.size} gehaltene Töne gefunden.")
        appendLine()
        appendLine("| Ton | Aufnahmen | f0 Hz | Teiltöne | " + (1..SHOWN).joinToString(" | ") { "H$it" } + " |")
        appendLine("|---|---:|---:|---:|" + "---:|".repeat(SHOWN))
        for (n in levels) {
            val takes = if (n.takes == 0) "ergänzt" else n.takes.toString()
            val shown = (0 until SHOWN).joinToString(" | ") { k -> n.levelsDb.getOrNull(k)?.let { db(it) }.orEmpty() }
            appendLine(
                "| ${NoteNames.germanOctaveName(n.midi)} | $takes | ${n.f0Hz?.let { de(it, 1) } ?: "–"} | " +
                    "${n.levelsDb.size} | $shown |"
            )
        }
    }

    /** Kotlin source of the table for `core/dsp` (see `MeasuredSpectrum`), object named after the [file]. */
    fun kotlin(file: File, instrument: String, source: String, a4Hz: Double, levels: List<NoteLevels>): String {
        require(levels.isNotEmpty()) { "no notes to write" }
        val name = file.nameWithoutExtension
        return buildString {
            appendLine("package io.github.blanaboo.stimmzug.dsp.synth")
            appendLine()
            appendLine("// Generated by tools/replay --spectrum from \"$source\" (a′ = ${f(a4Hz, 0)} Hz). Do not edit.")
            appendLine()
            appendLine("/** Harmonic levels of the $instrument, measured note by note (#72). */")
            appendLine("internal object $name {")
            appendLine("    val spectrum = MeasuredSpectrum(")
            appendLine("        name = \"$instrument\",")
            appendLine("        lowestMidi = ${levels.first().midi},")
            appendLine("        levelsDb = listOf(")
            for (n in levels) {
                val takes = if (n.takes == 0) "filled in from its neighbours" else "${n.takes} take(s)"
                appendLine("            // ${NoteNames.germanOctaveName(n.midi)} (MIDI ${n.midi}), $takes")
                appendLine("            MeasuredSpectrum.levels(")
                val lines = n.levelsDb.map { it.roundToInt().toString() }.chunked(VALUES_PER_LINE)
                lines.forEachIndexed { i, chunk ->
                    appendLine("                \"${chunk.joinToString(" ")}\"" + if (i < lines.lastIndex) "," else "")
                }
                appendLine("            )" + if (n === levels.last()) "" else ",")
            }
            appendLine("        )")
            appendLine("    )")
            appendLine("}")
        }
    }

    private fun f(value: Double, decimals: Int) = String.format(Locale.ROOT, "%.${decimals}f", value)

    private fun de(value: Double, decimals: Int) = String.format(Locale.GERMANY, "%.${decimals}f", value)

    private fun db(value: Double): String = value.roundToInt().toString()
}
